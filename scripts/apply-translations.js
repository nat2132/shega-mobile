function stripCr(line) {
  return line.endsWith('\r') ? line.slice(0, -1) : line;
}

function findSectionBoundaries(lines, sectionName) {
  const startPattern = new RegExp(`^\\s*${sectionName}:\\s*\\{\\s*$`);
  let startIdx = -1;
  let endIdx = -1;

  for (let i = 0; i < lines.length; i++) {
    if (startPattern.test(stripCr(lines[i]))) {
      startIdx = i;
      break;
    }
  }

  if (startIdx === -1) {
    return null;
  }

  let braceCount = 0;
  for (let i = startIdx; i < lines.length; i++) {
    const line = stripCr(lines[i]);
    for (const ch of line) {
      if (ch === '{') braceCount++;
      if (ch === '}') braceCount--;
    }
    if (braceCount === 0 && i > startIdx) {
      endIdx = i;
      break;
    }
  }

  if (endIdx === -1) {
    return null;
  }

  return { start: startIdx, end: endIdx };
}

function parseKeyValuePairs(lines) {
  const pairs = [];
  for (const line of lines) {
    const cleanLine = stripCr(line);
    const match = cleanLine.match(/^\s*'(.*?)':\s*'(.*)'\s*,?\s*$/);
    if (match) {
      pairs.push({ key: match[1], value: match[2], raw: cleanLine });
    }
  }
  return pairs;
}

function escapeValue(value) {
  return value.replace(/'/g, "\\'");
}

function makeLine(key, value) {
  const escaped = escapeValue(value);
  return `    '${key}': '${escaped}',`;
}

function canBeSimpleString(value) {
  return !value.includes("'") && !value.includes('\\');
}

function updateFile() {
  const content = fs.readFileSync(filePath, 'utf-8');
  const lines = content.split('\n');

  const sections = ['am', 'om', 'ti'];
  const results = {};

  for (const lang of sections) {
    const bounds = findSectionBoundaries(lines, lang);
    if (!bounds) {
      results[lang] = { updated: 0, added: 0, error: `Section "${lang}" not found` };
      continue;
    }

    const sectionLines = lines.slice(bounds.start + 1, bounds.end).map(stripCr);
    const pairs = parseKeyValuePairs(sectionLines);
    const keyToLine = new Map();
    for (let i = 0; i < sectionLines.length; i++) {
      const match = sectionLines[i].match(/^\s*'(.*?)':/);
      if (match) {
        keyToLine.set(match[1], i);
      }
    }

    const langTranslations = translations[lang];
    if (!langTranslations) {
      results[lang] = { updated: 0, added: 0, error: `No translations data for "${lang}"` };
      continue;
    }

    let updated = 0;
    let added = 0;

    const sortedKeys = Object.keys(langTranslations).sort();
    for (const key of sortedKeys) {
      const newValue = langTranslations[key];

      if (keyToLine.has(key)) {
        const lineIdx = keyToLine.get(key);
        const newLine = makeLine(key, newValue);
        sectionLines[lineIdx] = newLine;
        updated++;
      } else {
        const insertionLine = makeLine(key, newValue);
        let insertIdx = sectionLines.length - 1;
        for (let i = 0; i < sectionLines.length; i++) {
          const existingMatch = sectionLines[i].match(/^\s*'(.*?)':/);
          if (existingMatch) {
            if (key < existingMatch[1]) {
              insertIdx = i;
              break;
            }
          }
        }
        sectionLines.splice(insertIdx, 0, insertionLine);
        added++;
        keyToLine.set(key, insertIdx);
        for (const [k, idx] of keyToLine) {
          if (idx >= insertIdx && k !== key) {
            keyToLine.set(k, idx + 1);
          }
        }
      }
    }

    const updatedLines = [
      ...lines.slice(0, bounds.start + 1),
      ...sectionLines,
      ...lines.slice(bounds.end),
    ];
    lines.length = 0;
    lines.push(...updatedLines);

    results[lang] = { updated, added };
  }

  fs.writeFileSync(filePath, lines.join('\n'), 'utf-8');
  console.log('File written successfully.');

  console.log('\n=== Translation Update Summary ===');
  let totalUpdated = 0;
  let totalAdded = 0;
  for (const lang of sections) {
    const r = results[lang] || { updated: 0, added: 0 };
    totalUpdated += r.updated;
    totalAdded += r.added;
    console.log(`${lang}: ${r.updated} updated, ${r.added} added${r.error ? ' (' + r.error + ')' : ''}`);
  }
  console.log(`\nTotal: ${totalUpdated} keys updated, ${totalAdded} keys added across all sections`);
}

