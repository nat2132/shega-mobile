export const SettingsProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [theme, setThemeState] = useState<Theme>('midnight');
  const [language, setLanguageState] = useState<Language>('en');
  const [calendarType, setCalendarTypeState] = useState<CalendarType>('ethiopian');
  const [userProfile, setUserProfileState] = useState<UserProfile>({
    name: 'Alexander Mitchell',
    businessName: 'Stratos Inventory',
    avatarIndex: 0,
  });
  const [notifications, setNotificationsState] = useState<NotificationSettings>({
    stock: true,
    expiration: true,
    daily: true,
    credit: true,
    debt: true,
  });
  const [pin, setPinState] = useState<string | null>(null);

  // Load settings on mount
  useEffect(() => {
    const loadSettings = async () => {
      const savedTheme = await SecureStore.getItemAsync('settings_theme') as Theme;
      if (savedTheme) setThemeState(savedTheme);

      const savedLang = await SecureStore.getItemAsync('settings_language') as Language;
      if (savedLang) setLanguageState(savedLang);

      const savedCalendar = await SecureStore.getItemAsync('settings_calendar') as CalendarType;
      if (savedCalendar) setCalendarTypeState(savedCalendar);

      const savedProfile = await SecureStore.getItemAsync('settings_profile');
      if (savedProfile) setUserProfileState(JSON.parse(savedProfile));

      const savedNotes = await SecureStore.getItemAsync('settings_notifications');
      if (savedNotes) setNotificationsState(JSON.parse(savedNotes));

      const savedPin = await SecureStore.getItemAsync('settings_pin');
      if (savedPin) setPinState(savedPin);
    };
    loadSettings();
  }, []);

  const setTheme = async (val: Theme) => {
    setThemeState(val);
    await SecureStore.setItemAsync('settings_theme', val);
  };

  const setLanguage = async (val: Language) => {
    setLanguageState(val);
    await SecureStore.setItemAsync('settings_language', val);
  };

  const setCalendarType = async (val: CalendarType) => {
    setCalendarTypeState(val);
    await SecureStore.setItemAsync('settings_calendar', val);
  };

  const setUserProfile = async (val: UserProfile) => {
    setUserProfileState(val);
    await SecureStore.setItemAsync('settings_profile', JSON.stringify(val));
    await SecureStore.setItemAsync('user_avatarIndex', val.avatarIndex.toString());
  };

  const setNotifications = async (val: NotificationSettings) => {
    setNotificationsState(val);
    await SecureStore.setItemAsync('settings_notifications', JSON.stringify(val));
  };

  const setPin = async (val: string | null) => {
    setPinState(val);
    if (val) {
      await SecureStore.setItemAsync('settings_pin', val);
    } else {
      await SecureStore.deleteItemAsync('settings_pin');
    }
  };

  const t = (key: string, params?: Record<string, string>) => {
    let text = translations[language][key] || translations['en'][key] || key;
    if (params) {
      Object.keys(params).forEach(p => {
        text = text.replace(`{${p}}`, params[p]);
      });
    }
    return text;
  };

  const getThemeColors = (t: Theme) => {
    switch (t) {
      case 'midnight': return MidnightTheme;
      case 'emerald': return EmeraldTheme;
      case 'charcoal': return CharcoalTheme;
      case 'slate': return SlateTheme;
      case 'cocoa': return CocoaTheme;
      case 'dark': return DarkTheme;
      case 'light': return LightTheme;
      default: return MidnightTheme;
    }
  };

  const colors = getThemeColors(theme);

  return (
    <SettingsContext.Provider value={{
      theme, language, calendarType, userProfile, notifications, pin,
      setTheme, setLanguage, setCalendarType, setUserProfile, setNotifications, setPin, t, colors
    }}>
      {children}
    </SettingsContext.Provider>
  );
};

export const useSettings = () => {
  const context = useContext(SettingsContext);
  if (context === undefined) {
    throw new Error('useSettings must be used within a SettingsProvider');
  }
  return context;
};
