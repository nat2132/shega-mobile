/* A Proxy-backed fake database: every method is a no-op, rows reads return empty */
const mockDb: any = new Proxy({}, {
  get: (_t: any, prop: PropertyKey) => {
    if (prop === 'getFirstSync') return () => null;
    if (prop === 'getAllSync') return () => [];
    if (prop === 'withTransactionSync') return (fn: any) => fn();
    if (typeof prop === 'string' && /^(execSync|runSync|closeSync|deleteDatabaseSync)/.test(prop)) return () => undefined;
    if (typeof prop !== 'string') return undefined;
    return () => undefined;
  },
});

