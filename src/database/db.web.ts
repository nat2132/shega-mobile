// Web-platform stub for the mobile SQLite database.
//
// The real implementation (db.ts) uses expo-sqlite, whose web worker/wasm graph
// cannot be chunked by the Expo dev web server (Metro serializer "Worker chunk not
// found" assertion). Web builds resolve here instead (Metro prefers *.web.ts): the
// module mirrors db.ts exports via type-only references so expo-sqlite is never in
// the web bundle. Values are benign stubs that mimic an empty/in-memory database so
// the app shell, providers and pre-login screens render (data reads yield empties).
import type { SQLiteDatabase } from 'expo-sqlite';

